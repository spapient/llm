//! 构建期生成词汇表：`.config/lints/vocabulary.toml` → `$OUT_DIR/vocabulary.rs`。
//!
//! ADR 0022：词汇表在编译期解析一次，运行期只遍历 [`Table`] / [`Value`] 这棵树。读取与表达式
//! 生成的共享逻辑在 [`diagnostic::buildgen`]，本脚本只负责语料路径与外层 `vocabulary()` 包装。
//! 产物不保留 TOML 文本，运行期没有任何解析器。

use diagnostic::buildgen;
use std::path::PathBuf;

fn main() {
    run().unwrap_or_else(|error| panic!("{error}"));
}

fn run() -> diagnostic::Result<()> {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let source = manifest.join("../../.config/lints/vocabulary.toml");
    println!("cargo:rerun-if-changed=../../.config/lints/vocabulary.toml");
    let table = buildgen::read(&source)?;

    let mut code = String::new();
    code.push_str("// @generated by crates/tools/build.rs — do not edit.\n");
    code.push_str("// Source: .config/lints/vocabulary.toml.\n");
    code.push_str("use std::sync::OnceLock;\n\n");
    code.push_str("use diagnostic::data::{Table, Value};\n\n");
    code.push_str("/// 编译期生成的词汇表：`[closed]` / `[bitset]` / `[ownership]` / `[gate]`。\n");
    code.push_str("pub fn vocabulary() -> &'static Table {\n");
    code.push_str("    static VOCABULARY: OnceLock<Table> = OnceLock::new();\n");
    code.push_str("    VOCABULARY.get_or_init(|| ");
    code.push_str(&buildgen::emit(&table, "vocabulary")?);
    code.push_str(")\n");
    code.push_str("}\n");

    let out = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let target = out.join("vocabulary.rs");
    std::fs::write(&target, code)
        .unwrap_or_else(|error| panic!("写入 {} 失败：{error}", target.display()));
    Ok(())
}

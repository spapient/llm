//! 构建期生成强类型词汇表：`.config/lints/vocabulary.toml` → `$OUT_DIR/vocabulary.rs`。
//!
//! TOML 只在这里解析；产物是 `VocabularyView` 静态字段，运行期没有动态表树或解析器。

use diagnostic::buildgen;
use std::path::PathBuf;

fn main() {
    run().unwrap_or_else(|error| panic!("{error}"));
}

fn run() -> diagnostic::Result<()> {
    let manifest = PathBuf::from(buildgen::env_required("CARGO_MANIFEST_DIR")?);
    let source = manifest.join("../../.config/lints/vocabulary.toml");
    println!("cargo:rerun-if-changed=../../.config/lints/vocabulary.toml");
    let table = buildgen::read(&source)?;
    let code = render(&table)?;
    let out = PathBuf::from(buildgen::env_required("OUT_DIR")?);
    let target = out.join("vocabulary.rs");
    std::fs::write(&target, code)
        .unwrap_or_else(|error| panic!("写入 {} 失败：{error}", target.display()));
    Ok(())
}

/// 一张完整静态词汇表；每个配置段只投影到自己的强类型字段。
fn render(root: &toml::Table) -> diagnostic::Result<String> {
    let gate = gate(root)?;
    let closed = exemptions(root, "closed")?;
    let bitset = exemptions(root, "bitset")?;
    let ownership = unlisted(root)?;
    Ok(format!(
        "// @generated by crates/tools/build.rs — do not edit.\n\
         // Source: .config/lints/vocabulary.toml.\n\
         /// 编译期生成的完整词汇表。\n\
         pub const VOCABULARY: crate::gate::VocabularyView = crate::gate::VocabularyView {{\n\
         \x20   gate: {gate},\n\
         \x20   closed: {closed},\n\
         \x20   bitset: {bitset},\n\
         \x20   ownership_unlisted: {ownership},\n\
         }};\n\n\
         /// 读取编译期强类型词汇表。\n\
         pub fn vocabulary() -> &'static crate::gate::VocabularyView {{ &VOCABULARY }}\n"
    ))
}

/// `[gate]`：未知键与数值类型都在构建期拒绝。
fn gate(root: &toml::Table) -> diagnostic::Result<String> {
    let table = buildgen::subtable(root, "gate")?;
    for key in table.keys() {
        if !matches!(
            key.as_str(),
            "ccn_max"
                | "nloc_max"
                | "file_max_lines"
                | "file_min_lines"
                | "test_max_lines"
                | "debt"
                | "min_lines_baseline"
        ) {
            return Err(invalid(&format!("[gate] 未知键 {key}")));
        }
    }
    let ccn = integer(table, "ccn_max")?;
    let nloc = integer(table, "nloc_max")?;
    let file_max = integer(table, "file_max_lines")?;
    let file_min = integer(table, "file_min_lines")?;
    let test_max = integer(table, "test_max_lines")?;
    if file_min > file_max {
        return Err(invalid("[gate] file_min_lines 不能大于 file_max_lines"));
    }
    let debt = table
        .get("debt")
        .and_then(toml::Value::as_array)
        .map(|rows| {
            rows.iter()
                .map(debt_row)
                .collect::<diagnostic::Result<Vec<_>>>()
        })
        .transpose()?
        .unwrap_or_default();
    let baseline = table
        .get("min_lines_baseline")
        .and_then(toml::Value::as_array)
        .map(|rows| {
            rows.iter()
                .map(text)
                .collect::<diagnostic::Result<Vec<_>>>()
        })
        .transpose()?
        .unwrap_or_default();
    Ok(format!(
        "crate::gate::GateView {{ ccn_max:{ccn}, nloc_max:{nloc}, file_max_lines:{file_max}, \
         file_min_lines:{file_min}, test_max_lines:{test_max}, debt:{}, min_lines_baseline:{} }}",
        buildgen::expr_slice(&debt),
        buildgen::string_slice(&baseline),
    ))
}

/// 一条存量债：没有度量的行仍然报错。
fn debt_row(value: &toml::Value) -> diagnostic::Result<String> {
    let table = value
        .as_table()
        .ok_or_else(|| invalid("[gate.debt] 必须是表"))?;
    let key = buildgen::string(table, "key")?;
    let fields = ["ccn", "nloc", "lines", "call"].map(|key| optional(table, key));
    if fields.iter().all(|field| field == "None") {
        return Err(invalid(&format!("[gate.debt] {key} 无度量")));
    }
    Ok(format!(
        "crate::gate::DebtView {{ key:{key:?}, ccn:{}, nloc:{}, lines:{}, call:{} }}",
        fields[0], fields[1], fields[2], fields[3]
    ))
}

/// 闭集/位集合规条目。
fn exemptions(root: &toml::Table, section: &str) -> diagnostic::Result<String> {
    let table = buildgen::subtable(root, section)?;
    let rows = table
        .get("exempt")
        .and_then(toml::Value::as_array)
        .ok_or_else(|| invalid(&format!("[{section}] 缺 exempt 数组")))?;
    rows.iter()
        .map(|value| {
            let table = value.as_table().ok_or_else(|| invalid("exempt 必须是表"))?;
            let name = buildgen::string(table, "crate")?;
            let reason = buildgen::string(table, "reason")?;
            reasoned(reason)?;
            Ok(format!(
                "crate::gate::ExemptView {{ crate_name:{name:?}, reason:{reason:?} }}"
            ))
        })
        .collect::<diagnostic::Result<Vec<_>>>()
        .map(|rows| buildgen::expr_slice(&rows))
}

/// ownership 的存量条目：crate、名字数组与理由完整保留。
fn unlisted(root: &toml::Table) -> diagnostic::Result<String> {
    let rows = buildgen::subtable(root, "ownership")?
        .get("unlisted")
        .and_then(toml::Value::as_array)
        .ok_or_else(|| invalid("[ownership] 缺 unlisted 数组"))?;
    let entries = rows
        .iter()
        .map(|value| {
            let table = value
                .as_table()
                .ok_or_else(|| invalid("unlisted 必须是表"))?;
            let name = buildgen::string(table, "crate")?;
            let reason = buildgen::string(table, "reason")?;
            reasoned(reason)?;
            let names = table
                .get("names")
                .and_then(toml::Value::as_array)
                .ok_or_else(|| invalid("unlisted 缺 names 数组"))?
                .iter()
                .map(text)
                .collect::<diagnostic::Result<Vec<_>>>()?;
            Ok(format!(
                "crate::gate::UnlistedView {{ crate_name:{name:?}, names:{}, reason:{reason:?} }}",
                buildgen::string_slice(&names)
            ))
        })
        .collect::<diagnostic::Result<Vec<_>>>()?;
    Ok(buildgen::expr_slice(&entries))
}

/// 理由必须具体，不接受空泛占位。
fn reasoned(reason: &str) -> diagnostic::Result<()> {
    if reason.chars().count() < 8 {
        return Err(invalid("登记理由必须具体，不能短于 8 个字符"));
    }
    Ok(())
}

/// 字符串数组；不把非字符串静默转文本。
fn text(value: &toml::Value) -> diagnostic::Result<String> {
    value
        .as_str()
        .map(str::to_string)
        .ok_or_else(|| invalid("数组项必须是字符串"))
}

/// 正整数配置项；类型错误、负数和零共享既有错误口径。
fn integer(table: &toml::Table, key: &str) -> diagnostic::Result<usize> {
    table
        .get(key)
        .and_then(toml::Value::as_integer)
        .and_then(|value| usize::try_from(value).ok())
        .filter(|value| *value > 0)
        .ok_or_else(|| invalid(&format!("[gate] 缺正整数 {key}")))
}

/// 可选非负整数度量。
fn optional(table: &toml::Table, key: &str) -> String {
    table
        .get(key)
        .and_then(toml::Value::as_integer)
        .and_then(|value| usize::try_from(value).ok())
        .map_or_else(|| "None".to_string(), |value| format!("Some({value})"))
}

/// 配置错误统一为 `diagnostic::Error`，构建脚本主入口负责打印并失败。
fn invalid(message: &str) -> diagnostic::Error {
    diagnostic::Error::new(diagnostic::Code::Invalid, message).with("tools::build")
}

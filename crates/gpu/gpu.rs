/// The build-time kernel registry, generated by `build.rs`.
///
/// Every non-empty kernel source compiles to `OUT_DIR/fatbin/<stem>.o` at
/// build time and is embedded here as a `(source id, bytes)` pair, so the
/// fatbin-loading backends (MUSA, ROCm, CANN) find their images by id without
/// a filesystem at run time (docs/musa-backend-plan.md §5.3). Backends that
/// link their kernels as ordinary symbols (SYCL, MLU) never consult it. On
/// hosts without any fatbin-loading toolkit the registry is empty and
/// unreferenced; the cfg_attr keeps those hosts warning-free.
#[doc(hidden)]
#[cfg_attr(not(any(musa_toolkit, rocm_toolkit, cann_toolkit)), allow(dead_code))]
pub mod registry {
    include!(concat!(env!("OUT_DIR"), "/registry.rs"));
}


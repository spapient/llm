//! 构建期一次生成三棵树：档案表（`$OUT_DIR/embedded.rs`）、片段表（`$OUT_DIR/tables.rs`）
//! 与算子声明表（`$OUT_DIR/declared.rs`）。
//!
//! 三份语料同性质——都是「编译期解析一次、运行期只遍历 `Table`」（ADR 0022）——所以只有一个
//! 构建脚本：`src/<vendor>/<vendor>.toml` 回答"哪台设备"，`ops/*.toml` 回答"哪些算子"。
//!
//! 生成器必须在这里，因为 cargo 不允许一个包当自己的构建依赖：它曾经在独立 crate `frag` 里
//! （`use prof::…`），代价是一个 crate、一个 feature 与一张手写的六设备清单。搬进来之后
//! "哪台设备"由 `src/<vendor>/<vendor>.toml` 这个文件名回答——目录里有几份档案就有几台设备。
//!
//! 构建期校验替代运行期断言：签名声明对不上文件名、`(prim, impl)` 在档案里没有供给、见证入口
//! 缺失、尾块段不齐，全部在这里失败。ADR 0022：语料编译期解析一次，运行期只遍历 [`Table`]。
//!
//! 两处闭集不在这里核，因为构建脚本拿不到运行期类型：尾块六种形式的名字由
//! `prim/tests/fragments.rs` 对着 `Epilogue::ALL` 核（这里只核结构：恰六段、互不相同、六台
//! 设备一致）；原语名由生成的 `Prim::<变体>` 交给编译器核，写错的那一行在生成代码里编不过。

#[path = "src/sign.rs"]
mod sign;

#[path = "src/stems.rs"]
mod stems;

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use diagnostic::buildgen;
use stems::{EPILOGUE_STEM, WITNESS_STEM};

fn main() {
    let manifest = variable("CARGO_MANIFEST_DIR");
    let src = PathBuf::from(&manifest).join("src");
    let out = PathBuf::from(variable("OUT_DIR"));

    // 整棵树都算输入：新增一段片段、换一份见证都必须让构建脚本重跑。
    println!("cargo:rerun-if-changed={}", src.display());
    println!("cargo:rerun-if-env-changed=CARGO_FEATURE_DEVICE_IMAGE");
    println!("cargo:rerun-if-env-changed=CUTILE_REQUIRE_IMAGE");

    let devices = devices_of(&src);
    let images = env::var_os("CARGO_FEATURE_DEVICE_IMAGE").is_some();
    let tables = tables_of(&devices, &out, images);
    let declared = declarations_of(Path::new(&manifest));

    for (name, text) in [
        ("embedded.rs", archives_of(&devices)),
        ("tables.rs", tables),
        ("declared.rs", declared),
    ] {
        let path = out.join(name);
        fs::write(&path, text)
            .unwrap_or_else(|error| fail(format!("写 {} 失败：{error}", path.display())));
    }
}

// ── 算子声明表 ────────────────────────────────────────────────────────

/// 算子声明表：`ops/*.toml` → `$OUT_DIR/declared.rs`。
///
/// 产物只有一棵 `Table` 树与一张名字表，运行期无解析器（ADR 0022）；生成顺序按文件 stem 升序，
/// 所以 [`names`] 与注册表的顺序都可由文件名推出来。
fn declarations_of(manifest: &Path) -> String {
    declarations(manifest).unwrap_or_else(|error| fail(format!("算子声明表：{error}")))
}

fn declarations(manifest: &Path) -> diagnostic::Result<String> {
    let ops = manifest.join("src").join("ops");
    println!("cargo:rerun-if-changed={}", ops.display());
    let files = buildgen::collect(&ops)?;

    let mut code = String::new();
    code.push_str("// @generated by crates/prof/build.rs — do not edit.\n");
    code.push_str("// Source: crates/prof/ops/*.toml, sorted by file stem.\n");
    code.push_str("use std::sync::OnceLock;\n\n");
    code.push_str("use diagnostic::data::{Table, Value};\n\n");
    code.push_str("type Tables = Vec<(&'static str, Table)>;\n\n");
    code.push_str("fn tables() -> &'static Tables {\n");
    code.push_str("    static TABLES: OnceLock<Tables> = OnceLock::new();\n");
    code.push_str("    TABLES.get_or_init(|| {\n");
    code.push_str("        vec![\n");

    let mut names = Vec::new();
    for path in &files {
        println!(
            "cargo:rerun-if-changed={}",
            buildgen::relative(manifest, path)
        );
        let name = path
            .file_stem()
            .and_then(|stem| stem.to_str())
            .unwrap_or_else(|| panic!("`{}` 的文件名不是合法 UTF-8", path.display()));
        let table = resolve(&ops, buildgen::read(path)?)?;
        let _ = writeln!(
            code,
            "            (\"{name}\", {}),",
            buildgen::emit(&table, name)?
        );
        names.push(name);
    }

    code.push_str("        ]\n");
    code.push_str("    })\n");
    code.push_str("}\n\n");
    code.push_str("/// 按名字取编译期生成的声明表；名字不在表里时返回 `None`。\n");
    code.push_str("pub fn declared(name: &str) -> Option<&'static Table> {\n");
    code.push_str("    tables()\n");
    code.push_str("        .iter()\n");
    code.push_str("        .find(|(entry, _)| *entry == name)\n");
    code.push_str("        .map(|(_, table)| table)\n");
    code.push_str("}\n\n");
    let _ = writeln!(code, "static NAMES: [&str; {}] = [", names.len());
    for name in &names {
        let _ = writeln!(code, "    \"{name}\",");
    }
    code.push_str("];\n\n");
    code.push_str("/// 生成表里的算子名，按文件名升序。\n");
    code.push_str("pub fn names() -> &'static [&'static str] {\n");
    code.push_str("    &NAMES\n");
    code.push_str("}\n");
    Ok(code)
}

/// 解析 `base = "<name>"`：当前表先继承 `<name>.toml`，再被自己的键覆盖。
///
/// 兄弟继承（如 `gemv_i2` → `gemv_i4`）只差 `[op]`/`[consts]`/个别 `[needs]` 叶子，
/// `[needs]`/`[layouts]`/`[[variants]]` 一大段逐字相同，写在 base 里由继承共享。继承链可多级
/// （如 `adaptive_pool_f32` → `silu_f32` → `gelu_f32`），每级先展开自己的 base 再被当前表覆盖。
/// 声明语料无环，递归深度 ≤ 3。
fn resolve(ops: &Path, mut table: toml::Table) -> diagnostic::Result<toml::Table> {
    let Some(toml::Value::String(base)) = table.get("base").cloned() else {
        return Ok(table);
    };
    table.remove("base");
    let base = resolve(ops, buildgen::read(&ops.join(format!("{base}.toml")))?)?;
    Ok(merge(base, table))
}

/// 深度合并：`over` 覆盖 `base`，同名的子表递归合并（`[needs]` 只覆盖差的那一个叶子）。
fn merge(mut base: toml::Table, over: toml::Table) -> toml::Table {
    for (key, value) in over {
        match (base.get_mut(&key), value) {
            (Some(toml::Value::Table(inner)), toml::Value::Table(update)) => {
                *inner = merge(std::mem::take(inner), update);
            }
            (_, value) => {
                base.insert(key, value);
            }
        }
    }
    base
}

// ── 设备清单 ──────────────────────────────────────────────────────────

/// 一台设备：档案元数据、片段与路径（正文由生成的 `include_str!` 读，脚本里不再存一份）。
struct Device {
    /// vendor 名，同时是 `src/` 下的目录名与档案文件名。
    name: String,
    /// 片段与见证的扩展名，由目录里的见证文件决定。
    ext: String,
    /// 档案 `[meta]` 里要写进设备行的那三项。
    emit: String,
    tool: String,
    tool_ver: String,
    /// 原语名 → 片段路径，按原语名升序。
    fragments: Vec<(String, PathBuf)>,
    /// 原语名 → 见证入口，顺序同 [`Device::fragments`]。
    entries: Vec<(String, String)>,
    /// 写回尾块片段：一份文本，六种形式按 `/* epi: <form> */` 分段。
    epilogue: PathBuf,
    /// 见证源码与它的档案：生成的代码按路径读，构建期再按路径校。
    witness: PathBuf,
    archive: PathBuf,
    /// 尾块六段的名字，按出现顺序。
    forms: Vec<String>,
}

/// 目录里的设备：一个子目录一台，顺序按目录名升序（产物稳定）。
fn devices_of(src: &Path) -> Vec<Device> {
    let entries = fs::read_dir(src)
        .unwrap_or_else(|error| fail(format!("读取 {} 失败：{error}", src.display())));
    let mut dirs: Vec<PathBuf> = entries
        .map(|entry| {
            entry
                .unwrap_or_else(|error| fail(format!("读取 {} 的目录项失败：{error}", src.display())))
                .path()
        })
        .filter(|path| path.is_dir() && has_witness(path))
        .collect();
    dirs.sort();
    if dirs.is_empty() {
        fail(format!("`{}` 里一台设备都没有", src.display()));
    }

    let mut out: Vec<Device> = Vec::new();
    for dir in &dirs {
        let name = dir
            .file_name()
            .and_then(|value| value.to_str())
            .unwrap_or_else(|| fail(format!("`{}` 的目录名不是合法 UTF-8", dir.display())));
        if !identifier(name) {
            fail(format!("设备目录名 `{name}` 不是可移植的 Rust 标识符"));
        }
        let device = scan(dir, name);
        // 六台设备的尾块必须是同一组形式：装配器按名字取段，缺一处就只在那一台上炸。
        match out.first() {
            Some(first) if first.forms != device.forms => fail(format!(
                "`{name}` 的尾块分段是 [{}]，与 `{}` 的 [{}] 不一致",
                device.forms.join(", "),
                first.name,
                first.forms.join(", ")
            )),
            _ => out.push(device),
        }
    }
    out
}

/// 扫描一台设备的目录：七段原语片段 + `epilogue.<ext>` + `witness.<ext>` + 同名档案。
fn scan(dir: &Path, name: &str) -> Device {
    let files = files_in(dir);
    let witness = files
        .iter()
        .find(|path| stem(path) == Some(WITNESS_STEM))
        .cloned()
        .unwrap_or_else(|| {
            fail(format!(
                "`{}` 里没有 `{WITNESS_STEM}.<ext>`：设备目录必须带上见证，否则映射表没有入口可指",
                dir.display()
            ))
        });
    let ext = extension(&witness)
        .unwrap_or_else(|| fail(format!("`{}` 没有扩展名", witness.display())));

    let doc = archive_of(dir, name);
    let meta = doc
        .get("meta")
        .and_then(|value| value.as_table())
        .unwrap_or_else(|| fail(format!("`{name}` 的档案没有 `[meta]` 表")));
    let provides = provides_of(&doc, name, &ext);
    let archive = dir.join(format!("{name}.toml"));

    let mut fragments = Vec::new();
    let mut entries = Vec::new();
    let mut epilogue = None;
    for path in files.iter().filter(|path| **path != witness && **path != archive) {
        let prim = stem(path)
            .unwrap_or_else(|| fail(format!("`{}` 的文件名不是合法 UTF-8", path.display())))
            .to_string();
        if extension(path).as_deref() != Some(ext.as_str()) {
            fail(format!(
                "`{}` 的扩展名与同目录的 `{WITNESS_STEM}.{ext}` 不一致：一台设备只有一种输出语言",
                path.display()
            ));
        }
        if prim == EPILOGUE_STEM {
            epilogue = Some(path.clone());
            continue;
        }
        let implementation = signature(&prim, &read(path), path);
        entries.push((prim.clone(), entry_of(&provides, &prim, &implementation, path)));
        fragments.push((prim, path.clone()));
    }
    if fragments.is_empty() {
        fail(format!("`{}` 里一段片段都没有", dir.display()));
    }
    let epilogue = epilogue.unwrap_or_else(|| {
        fail(format!(
            "`{}` 里没有 `{EPILOGUE_STEM}.{ext}`：六种写回形式没有片段，装配无从下手",
            dir.display()
        ))
    });
    fragments.sort();
    entries.sort();

    let forms = forms_of(&read(&epilogue), &epilogue);
    Device {
        name: name.to_string(),
        ext,
        emit: text(meta, "emit", name),
        tool: text(meta, "tools", name),
        tool_ver: meta
            .get("tool_ver")
            .and_then(|value| value.as_str())
            .unwrap_or("-")
            .to_string(),
        fragments,
        entries,
        epilogue,
        witness,
        archive,
        forms,
    }
}

/// 目录对应的档案：`src/<vendor>/<vendor>.toml`，目录名与 `meta.vendor` 必须一致。
fn archive_of(dir: &Path, name: &str) -> toml::Table {
    let path = dir.join(format!("{name}.toml"));
    if !path.is_file() {
        fail(format!(
            "`{}` 没有同名档案 `{name}.toml`：目录名就是 vendor，档案必须同名",
            dir.display()
        ));
    }
    let doc = buildgen::read(&path).unwrap_or_else(|error| fail(format!("{error}")));
    let vendor = doc
        .get("meta")
        .and_then(|value| value.as_table())
        .and_then(|meta| meta.get("vendor"))
        .and_then(|value| value.as_str())
        .unwrap_or_else(|| fail(format!("`{name}` 的档案没有 `meta.vendor`")));
    if vendor != name {
        fail(format!(
            "档案 `{name}.toml` 的 `meta.vendor` 是 `{vendor}`：目录名与 vendor 必须一致"
        ));
    }
    doc
}

/// 一条 `[[provides]]` 里生成期要核的三件事：签名、见证入口、见证文件。
struct Provide {
    prim: String,
    imp: String,
    func: String,
}

fn provides_of(doc: &toml::Table, name: &str, ext: &str) -> Vec<Provide> {
    let want = format!("{name}/{WITNESS_STEM}.{ext}");
    doc.get("provides")
        .and_then(|value| value.as_array())
        .unwrap_or_else(|| fail(format!("`{name}` 的档案没有 `[[provides]]`")))
        .iter()
        .map(|entry| {
            let table = entry
                .as_table()
                .unwrap_or_else(|| fail(format!("`{name}` 的 `provides` 里有非表条目")));
            let witness = table
                .get("witness")
                .and_then(|value| value.as_table())
                .unwrap_or_else(|| {
                    fail(format!("`{name}` 的档案有 `provides` 缺 `witness`：写回证据必须可指"))
                });
            let file = text(witness, "file", name);
            if file != want {
                fail(format!(
                    "`{name}` 的 `witness.file` 是 `{file}`：必须是 `{want}`（档案与目录必须同名）"
                ));
            }
            Provide {
                prim: text(table, "prim", name),
                imp: text(table, "impl", name),
                func: text(witness, "func", name),
            }
        })
        .collect()
}

/// 原语在设备镜像里的入口：档案里 `(prim, impl)` 那条供给的见证函数名。
fn entry_of(provides: &[Provide], prim: &str, implementation: &str, path: &Path) -> String {
    provides
        .iter()
        .find(|provide| provide.prim == prim && provide.imp == implementation)
        .map(|provide| provide.func.clone())
        .unwrap_or_else(|| {
            let declared: Vec<&str> = provides
                .iter()
                .filter(|provide| provide.prim == prim)
                .map(|provide| provide.imp.as_str())
                .collect();
            fail(format!(
                "`{}` 声明的签名 `{prim}/{implementation}` 在档案里没有对应 `provides`\
                 （档案里 `{prim}` 的实现：{}）",
                path.display(),
                if declared.is_empty() {
                    "一条都没有".to_string()
                } else {
                    declared.join(", ")
                }
            ))
        })
}

/// 片段第一行的签名声明：`/* cutile-sign: <prim>/<impl> */`。返回 `impl` 名。
fn signature(prim: &str, source: &str, path: &Path) -> String {
    let first = source.lines().next().unwrap_or_default();
    let declared = sign::strip_marker(first).unwrap_or_else(|| {
        fail(format!(
            "`{}` 的第一行必须是 `/* {} {prim}/<impl> */`，实际是 `{first}`",
            path.display(),
            sign::MARKER
        ))
    });
    let (declared_prim, implementation) = sign::split_slash(declared)
        .unwrap_or_else(|| fail(format!("`{}` 的签名声明不是 `<prim>/<impl>`", path.display())));
    if declared_prim.trim() != prim {
        fail(format!(
            "`{}` 的签名声明写的是 `{}`：文件名即原语名，两者必须一致",
            path.display(),
            declared_prim.trim()
        ));
    }
    let implementation = implementation.trim();
    if implementation.is_empty() {
        fail(format!("`{}` 的签名声明缺少 `impl` 名", path.display()));
    }
    implementation.to_string()
}

/// 尾块正文里的六段标记：数量与名字在这里核，名字属于闭集由 `prim` 的测试核。
fn forms_of(source: &str, path: &Path) -> Vec<String> {
    let mut forms: Vec<String> = Vec::new();
    for (index, marker) in source.match_indices("/* epi: ").collect::<Vec<_>>() {
        let _ = marker;
        let name = source[index + "/* epi: ".len()..]
            .split(" */")
            .next()
            .unwrap_or_default()
            .trim();
        if name.is_empty() {
            fail(format!("`{}` 有空的分段标记", path.display()));
        }
        if forms.iter().any(|have| have == name) {
            fail(format!("`{}` 的尾块分段 `{name}` 出现了两次", path.display()));
        }
        forms.push(name.to_string());
    }
    if forms.len() != 6 {
        fail(format!(
            "`{}` 有 {} 段尾块（`/* epi: <form> */`），六种写回形式必须齐全",
            path.display(),
            forms.len()
        ));
    }
    forms
}

// ── 文件与环境变量 ────────────────────────────────────────────────────

/// 列出目录里的文件并排序；单个条目读失败显式失败——静默跳过会让生成的表缺项而构建仍绿。
fn files_in(dir: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    for entry in fs::read_dir(dir)
        .unwrap_or_else(|error| fail(format!("读取 {} 失败：{error}", dir.display())))
    {
        let entry = entry
            .unwrap_or_else(|error| fail(format!("读取 {} 的目录项失败：{error}", dir.display())));
        let path = entry.path();
        if path.is_file() {
            out.push(path);
        }
    }
    out.sort();
    out
}

/// 只有带见证文件的目录才是设备目录：`src/` 里除了六台设备的语料，还有 `decl`/`ops` 这类
/// 非设备子树（声明解析与算子语料），它们不含 `witness.<ext>`，不得被当成设备扫描。
fn has_witness(dir: &Path) -> bool {
    files_in(dir).iter().any(|path| stem(path) == Some(WITNESS_STEM))
}

fn read(path: &Path) -> String {
    fs::read_to_string(path)
        .unwrap_or_else(|error| fail(format!("读取 {} 失败：{error}", path.display())))
}

fn stem(path: &Path) -> Option<&str> {
    path.file_stem().and_then(|value| value.to_str())
}

fn extension(path: &Path) -> Option<String> {
    path.extension()
        .and_then(|value| value.to_str())
        .map(str::to_string)
}

fn text(table: &toml::Table, key: &str, name: &str) -> String {
    table
        .get(key)
        .and_then(|value| value.as_str())
        .unwrap_or_else(|| fail(format!("`{name}` 的档案缺少字符串键 `{key}`")))
        .to_string()
}

/// 构建脚本必带的环境变量；缺了说明调用方不是 `build.rs`，直接失败而不是猜一个目录。
fn variable(name: &str) -> String {
    env::var(name).unwrap_or_else(|_| fail(format!("{name} 未设置：只有 build.rs 会读它")))
}

/// 目录名要能直接写进生成的代码：标识符形状，且不是 Rust 关键字。
fn identifier(name: &str) -> bool {
    const KEYWORDS: &[&str] = &[
        "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum",
        "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move",
        "mut", "pub", "ref", "return", "self", "static", "struct", "super", "trait", "true",
        "type", "unsafe", "use", "where", "while",
    ];
    let mut chars = name.chars();
    chars
        .next()
        .is_some_and(|first| first == '_' || first.is_ascii_alphabetic())
        && chars.all(|rest| rest == '_' || rest.is_ascii_alphanumeric())
        && !KEYWORDS.contains(&name)
}

/// 文件名里的原语名 → `Prim` 变体名：`load_async` → `LoadAsync`。
///
/// 名字对不对不靠这里判断：生成的代码写的是 `Prim::<变体>`，写错的原语在这一行编不过。
fn variant(name: &str) -> String {
    let mut out = String::new();
    let mut upper = true;
    for ch in name.chars() {
        if ch == '_' {
            upper = true;
        } else {
            out.push(if upper { ch.to_ascii_uppercase() } else { ch });
            upper = false;
        }
    }
    out
}

/// 构建期失败：报给 `cargo` 并以非零码结束，`build.rs` 因此失败。
fn fail(message: impl std::fmt::Display) -> ! {
    eprintln!("prof::build: {message}");
    std::process::exit(1)
}

// ── 档案表 ────────────────────────────────────────────────────────────

/// ADR 0022 的档案树：`Table::from_pairs(vec![…])` 字面量 + 一张按名字查的表。
fn archives_of(devices: &[Device]) -> String {
    let mut code = String::from(
        "// @generated by crates/prof/build.rs — do not edit.\n\
         // Source: crates/prof/src/<vendor>/<vendor>.toml, sorted by vendor.\n\
         use std::sync::OnceLock;\n\n\
         use diagnostic::data::{Table, Value};\n\n\
         type Tables = Vec<(&'static str, Table)>;\n\n\
         fn tables() -> &'static Tables {\n\
         \x20   static TABLES: OnceLock<Tables> = OnceLock::new();\n\
         \x20   TABLES.get_or_init(|| {\n\
         \x20       vec![\n",
    );
    for device in devices {
        let table = buildgen::read(&device.archive).unwrap_or_else(|error| fail(format!("{error}")));
        let pairs = buildgen::emit(&table, &device.name).unwrap_or_else(|error| fail(format!("{error}")));
        let _ = writeln!(code, "            ({:?}, {pairs}),", device.name);
    }
    code.push_str(
        "        ]\n\
         \x20   })\n\
         }\n\n\
         /// 按名字取编译期生成的档案表；名字不在表里时返回 `None`。\n\
         pub fn embedded(name: &str) -> Option<&'static Table> {\n\
         \x20   tables()\n\
         \x20       .iter()\n\
         \x20       .find(|(entry, _)| *entry == name)\n\
         \x20       .map(|(_, table)| table)\n\
         }\n\n",
    );
    let _ = writeln!(code, "static NAMES: [&str; {}] = [", devices.len());
    for device in devices {
        let _ = writeln!(code, "    {:?},", device.name);
    }
    code.push_str(
        "];\n\n\
         /// 生成表里的档案名，按 vendor 升序。\n\
         pub fn names() -> &'static [&'static str] {\n\
         \x20   &NAMES\n\
         }\n",
    );
    code
}

// ── 片段表 ────────────────────────────────────────────────────────────

/// 每台设备一个模块：片段、入口、尾块、源码根与设备行；末尾再合成四张聚合表。
fn tables_of(devices: &[Device], out: &Path, images: bool) -> String {
    let mut text = String::from(
        "// 由 `crates/prof/build.rs` 生成，不要手改。\n\
         //\n\
         // 每台设备一个模块：片段、入口、设备行与源码根；本文件末尾再把它们合成 `BUILTIN` /\n\
         // `WITNESS` / `DEVICES` / `ROOTS`。类型定义在 `src/`，所以生成代码不改变所有权表。\n",
    );
    for device in devices {
        // 镜像结局只算一次：生成的表与 `CUTILE_REQUIRE_IMAGE` 门禁读的是同一次编译的结果。
        let outcome = outcome(device, out, images);
        let _ = writeln!(
            text,
            "\n/// `{}` 设备的片段：原语 → 文本、原语 → 见证入口、设备行与源码根。\npub mod {} {{\n\
             #[allow(unused_imports)]\n\
             use crate::atom::Prim;\n\n\
             /// 本设备片段与见证所在目录，`prim` 按它读磁盘。\n\
             pub const ROOT: &str = concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/src/{}\");",
            device.name, device.name, device.name
        );
        fragments(&mut text, device);
        let _ = writeln!(
            text,
            "/// 写回尾块片段：`/* epi: <form> */` 分成六段，装配按段取用。\n\
             pub const EPILOGUE: &str = include_str!({:?});\n",
            device.epilogue.display().to_string()
        );
        prims(&mut text, device);
        device_line(&mut text, device, &outcome);
        text.push_str("}\n");
        require(device, &outcome);
    }
    aggregates(&mut text, devices);
    text
}

/// 片段表：`(原语, 文本)`，按原语名升序。
fn fragments(text: &mut String, device: &Device) {
    let _ = writeln!(
        text,
        "/// 片段：原语 → 文本，按原语名升序。\npub const FRAGMENTS: [(Prim, &str); {}] = [",
        device.fragments.len()
    );
    for (prim, path) in &device.fragments {
        let _ = writeln!(
            text,
            "    (Prim::{}, include_str!({:?})),",
            variant(prim),
            path.display().to_string()
        );
    }
    text.push_str("];\n");
}

/// 入口表：原语 → 见证里的入口名，顺序同 [`fragments`]。
fn prims(text: &mut String, device: &Device) {
    let _ = writeln!(
        text,
        "/// 原语 → 见证里的入口名：镜像里查的就是这个名字。\n\
         pub const PRIMS: [(Prim, &str); {}] = [",
        device.entries.len()
    );
    for (prim, entry) in &device.entries {
        let _ = writeln!(text, "    (Prim::{}, {entry:?}),", variant(prim));
    }
    text.push_str("];\n");
}

/// 设备行：入口表 + 档案元数据 + 见证源码 +（可选的）镜像 + 结局。
fn device_line(text: &mut String, device: &Device, outcome: &Outcome) {
    let _ = writeln!(
        text,
        "/// 设备行：本文件末尾把它连同另外几台设备合成 `DEVICES`。\n\
         pub const DEVICE: crate::Device = crate::Device {{\n\
         \x20   vendor: {:?},\n\
         \x20   ext: {:?},\n\
         \x20   emit: {:?},\n\
         \x20   tool: {:?},\n\
         \x20   tool_ver: {:?},\n\
         \x20   prims: &PRIMS,\n\
         \x20   epilogue: EPILOGUE,\n\
         \x20   source: include_str!({:?}),",
        device.name,
        device.ext,
        device.emit,
        device.tool,
        device.tool_ver,
        device.witness.display().to_string()
    );
    match outcome {
        Outcome::Compiled { path, symbols } => {
            let format = recipe(&device.emit).map_or("", |recipe| recipe.format);
            let _ = writeln!(
                text,
                "    image: Some(crate::Image::new({format:?}, include_bytes!({:?}), {symbols})),\n\
                 \x20   status: crate::Status::Compiled,",
                path.display().to_string()
            );
        }
        Outcome::Source => text.push_str("    image: None,\n    status: crate::Status::Source,\n"),
        Outcome::NoRecipe => text.push_str("    image: None,\n    status: crate::Status::NoRecipe,\n"),
        Outcome::Skipped(reason) => {
            let _ = writeln!(
                text,
                "    image: None,\n    status: crate::Status::Skipped {{ reason: {reason:?} }},"
            );
        }
    }
    text.push_str("};\n");
}

/// 四张聚合表：`prim` 拿它们回答"有哪些设备"与"这台设备的片段是什么"。
///
/// 长度由生成的模块数决定，不写死台数：加一份 `<vendor>.toml` 就多一台设备。
fn aggregates(text: &mut String, devices: &[Device]) {
    let count = devices.len();
    let names: Vec<&str> = devices.iter().map(|device| device.name.as_str()).collect();

    let _ = writeln!(
        text,
        "\n/// 每台设备的内嵌片段：`(vendor, ext, 片段)`。\npub const BUILTIN: [crate::Builtin; {count}] = ["
    );
    for name in &names {
        let _ = writeln!(
            text,
            "    crate::Builtin {{ vendor: {name}::DEVICE.vendor, ext: {name}::DEVICE.ext, \
             fragments: &{name}::FRAGMENTS }},"
        );
    }
    text.push_str("];\n");

    let _ = writeln!(
        text,
        "\n/// 内嵌的见证源码：`(vendor, ext, 文本)`。\npub const WITNESS: [(&str, &str, &str); {count}] = ["
    );
    for name in &names {
        let _ = writeln!(
            text,
            "    ({name}::DEVICE.vendor, {name}::DEVICE.ext, {name}::DEVICE.source),"
        );
    }
    text.push_str("];\n");

    let _ = writeln!(
        text,
        "\n/// 每台设备一行：vendor、输出语言、工具链、入口表、见证源码与（可选的）设备镜像。\n\
         pub static DEVICES: [crate::Device; {count}] = ["
    );
    for name in &names {
        let _ = writeln!(text, "    {name}::DEVICE,");
    }
    text.push_str("];\n");

    let _ = writeln!(
        text,
        "\n/// 每台设备的源码根目录：`(vendor, 目录)`。\npub const ROOTS: [(&str, &str); {count}] = ["
    );
    for name in &names {
        let _ = writeln!(text, "    ({name}::DEVICE.vendor, {name}::ROOT),");
    }
    text.push_str("];\n");
}

// ── 设备镜像 ──────────────────────────────────────────────────────────

/// 一台设备的镜像结局。
enum Outcome {
    /// 未开启 `device-image`：只有源码。
    Source,
    /// 这台设备的输出语言还没有构建配方。
    NoRecipe,
    /// 有配方，但工具链不在本机或编译失败。
    Skipped(String),
    /// 编好了。
    Compiled { path: PathBuf, symbols: usize },
}

/// 按输出语言编设备镜像：`witness.<ext>` → 中间产物 → 镜像。
fn outcome(device: &Device, out: &Path, images: bool) -> Outcome {
    if !images {
        return Outcome::Source;
    }
    match recipe(&device.emit) {
        None => Outcome::NoRecipe,
        Some(recipe) => compile(device, recipe, out).unwrap_or_else(Outcome::Skipped),
    }
}

/// 编译一台设备的见证：`[meta].tools` 给出的程序 + 配方里的参数。
fn compile(device: &Device, recipe: &Recipe, out: &Path) -> Result<Outcome, String> {
    let mut parts = device.tool.split_whitespace();
    let Some(program) = parts.next() else {
        return Err(format!("`{}` 不是可执行的工具名", device.tool));
    };
    let object = out.join(format!("{}.witness.{}", device.name, recipe.object_ext));
    let image = out.join(format!("{}.witness.{}", device.name, recipe.format));

    let mut args: Vec<String> = parts.map(str::to_string).collect();
    args.extend(
        recipe
            .compile
            .iter()
            .map(|arg| expand(arg, &device.witness, &object, &image)),
    );
    run(program, &args)?;

    if let Some((linker, link_args)) = recipe.link {
        let args: Vec<String> = link_args
            .iter()
            .map(|arg| expand(arg, &device.witness, &object, &image))
            .collect();
        run(linker, &args)?;
    }

    let symbols = recipe
        .inspect
        .and_then(|(inspector, inspect_args)| {
            let args: Vec<String> = inspect_args
                .iter()
                .map(|arg| expand(arg, &device.witness, &object, &image))
                .collect();
            run(inspector, &args).ok()
        })
        .map(|stdout| stdout.lines().filter(|line| line.contains(" T ")).count())
        .unwrap_or(0);

    Ok(Outcome::Compiled { path: image, symbols })
}

/// 一条语言级的构建配方：怎么把一份翻译单元变成设备镜像。
struct Recipe {
    /// 编译参数（`$src` / `$obj`）。
    compile: &'static [&'static str],
    /// 链接一步：程序与参数（`$obj` / `$out`）。
    link: Option<(&'static str, &'static [&'static str])>,
    /// 中间产物的扩展名。
    object_ext: &'static str,
    /// 镜像格式名。
    format: &'static str,
    /// 符号统计：程序与参数（`$obj`），每行一个符号，` T ` 是已定义的文本符号。
    inspect: Option<(&'static str, &'static [&'static str])>,
}

/// 有构建配方的输出语言。其余语言只有源码：`Status::NoRecipe` 是它们的诚实答案。
const RECIPES: &[(&str, Recipe)] = &[(
    "metal",
    Recipe {
        compile: &["-c", "$src", "-o", "$obj"],
        link: Some(("xcrun", &["metallib", "$obj", "-o", "$out"])),
        object_ext: "air",
        format: "metallib",
        inspect: Some(("xcrun", &["metal-nm", "$obj"])),
    },
)];

fn recipe(emit: &str) -> Option<&'static Recipe> {
    RECIPES
        .iter()
        .find(|(language, _)| *language == emit)
        .map(|(_, recipe)| recipe)
}

/// 占位符替换：`$src` / `$obj` / `$out`。
fn expand(arg: &str, src: &Path, object: &Path, image: &Path) -> String {
    arg.replace("$src", &src.display().to_string())
        .replace("$obj", &object.display().to_string())
        .replace("$out", &image.display().to_string())
}

/// 跑一个子进程；失败时把第一行 stderr 作为原因交回（构建不因此失败）。
fn run(program: &str, args: &[String]) -> Result<String, String> {
    let output = Command::new(program)
        .args(args)
        .output()
        .map_err(|error| format!("`{program}` 不可执行：{error}"))?;
    if output.status.success() {
        return Ok(String::from_utf8_lossy(&output.stdout).into_owned());
    }
    let stderr = String::from_utf8_lossy(&output.stderr);
    let first = stderr
        .lines()
        .find(|line| !line.trim().is_empty())
        .unwrap_or("");
    Err(format!(
        "`{program} {}` 失败（{}）：{}",
        args.join(" "),
        output.status,
        shorten(first)
    ))
}

/// 原因只留一行、最多 160 字符：它要进生成的代码。
fn shorten(text: &str) -> String {
    let text = text.trim();
    if text.chars().count() <= 160 {
        return text.to_string();
    }
    let cut: String = text.chars().take(157).collect();
    format!("{cut}...")
}

/// `CUTILE_REQUIRE_IMAGE` 要求了这台设备就必须真的带上镜像。
fn require(device: &Device, outcome: &Outcome) {
    let required = env::var("CUTILE_REQUIRE_IMAGE").ok().is_some_and(|text| {
        text.split(',')
            .map(str::trim)
            .any(|name| name == device.name)
    });
    if !required {
        return;
    }
    match outcome {
        Outcome::Compiled { .. } => {}
        Outcome::Source => fail(format!(
            "`CUTILE_REQUIRE_IMAGE` 要求 `{}` 的设备镜像，但构建没有开 `device-image`",
            device.name
        )),
        Outcome::NoRecipe => fail(format!(
            "`CUTILE_REQUIRE_IMAGE` 要求 `{}` 的设备镜像，但它的输出语言还没有构建配方",
            device.name
        )),
        Outcome::Skipped(reason) => fail(format!(
            "`CUTILE_REQUIRE_IMAGE` 要求 `{}` 的设备镜像，但它没有编出来：{reason}",
            device.name
        )),
    }
}
